"""D 版页面构建；业务事件由 HeartAppWindow 处理。"""
from __future__ import annotations

from PySide6.QtCore import Qt
from PySide6.QtWidgets import (QAbstractItemView, QCheckBox, QComboBox, QDialog, QFrame,
    QHBoxLayout, QHeaderView, QLabel, QLineEdit, QSlider, QStackedWidget,
    QTableWidget, QVBoxLayout, QWidget)

from ... import __version__
from ...simulator import DEFAULT_PROFILE, PROFILES
from .editorial import BrandMark, Button, CapsuleCombo, Curve, INK, MUTED, Navigation, PAPER, RED, RULE, Reading, label, serif
from .chrome import TitleBar


class EditorialLayout:
    def _build_ui(self) -> None:
        self.setStyleSheet(f"QLabel, QCheckBox {{ color: {INK}; background: transparent; }} QDialog {{ background: {PAPER}; }} "
            f"QLineEdit, QComboBox {{ color: {INK}; background: {PAPER}; border: 1px solid {RULE}; padding: 7px; border-radius: 4px; }} "
            f"QToolTip {{ background: {PAPER}; color: {INK}; border: 1px solid {RULE}; }} "
            f"QComboBox QAbstractItemView {{ color: {INK}; background: {PAPER}; selection-background-color: #F8EAE4; selection-color: {INK}; }} "
            f"QCheckBox {{ spacing: 8px; }} QCheckBox::indicator {{ width: 16px; height: 16px; border: 1px solid #A8A095; border-radius: 3px; background: {PAPER}; }} "
            f"QCheckBox::indicator:checked {{ background: {RED}; border-color: {RED}; }} "
            f"QSlider::groove:horizontal {{ height: 3px; background: {RULE}; }} "
            f"QSlider::sub-page:horizontal {{ background: {RED}; }} "
            f"QSlider::handle:horizontal {{ background: {RED}; border: 3px solid {PAPER}; width: 10px; margin: -6px 0; border-radius: 8px; }}")
        outer = QVBoxLayout(self)
        outer.setContentsMargins(36, 16, 36, 16)
        outer.setSpacing(12)
        self._titlebar = TitleBar(self)
        header = self._titlebar.row
        mark = BrandMark()
        mark.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
        header.addWidget(mark)
        brand = label("HeartApp")
        brand.setFont(serif(25))
        brand.setAttribute(Qt.WidgetAttribute.WA_TransparentForMouseEvents)
        header.addWidget(brand)
        header.addStretch()
        self._tabbar = Navigation()
        self._tabbar.changed.connect(self._on_tab_changed)
        header.addWidget(self._tabbar)
        header.addSpacing(22)
        self._device_status = Button("●  连接手表")
        self._device_status.clicked.connect(self._show_connection)
        header.addWidget(self._device_status)
        self._titlebar.add_controls()
        outer.addWidget(self._titlebar)
        outer.addWidget(self._rule())
        self._build_connection_dialog()
        self._stack = QStackedWidget()
        self._stack.addWidget(self._build_live_page())
        self._stack.addWidget(self._build_history_page())
        self._stack.addWidget(self._build_overlay_page())
        from .room_panel import RoomPanel
        self._room_panel = RoomPanel(self)
        self._stack.addWidget(self._room_panel)
        outer.addWidget(self._stack, 1)
        outer.addWidget(self._rule())
        foot = QHBoxLayout()
        self._status_label = label("连接手表，开始记录你的心率变化。", 11, True)
        self._status_label.setWordWrap(True)
        foot.addWidget(self._status_label, 1)
        version = label(f"HeartApp   v{__version__}", 11, True)
        version.setToolTip(str(self.db_path))
        foot.addWidget(version)
        outer.addLayout(foot)

    @staticmethod
    def _rule(vertical: bool = False) -> QFrame:
        frame = QFrame()
        frame.setStyleSheet(f"background: {RULE};")
        if vertical:
            frame.setFixedWidth(1)
        else:
            frame.setFixedHeight(1)
        return frame

    def _on_tab_changed(self, index: int) -> None:
        self._stack.setCurrentIndex(index)
        if index == 1:
            self._refresh_history()

    def _show_connection(self) -> None:
        self._connection_dialog.show()
        self._connection_dialog.raise_()
        self._connection_dialog.activateWindow()

    def _build_connection_dialog(self) -> None:
        self._connection_dialog = QDialog(self)
        self._connection_dialog.setWindowTitle("连接心率设备")
        self._connection_dialog.setMinimumWidth(480)
        layout = QVBoxLayout(self._connection_dialog)
        layout.setContentsMargins(28, 24, 28, 24)
        layout.setSpacing(16)
        layout.addWidget(label("选择你的心率来源", 20))
        note = label("手表需开启标准蓝牙心率广播。没有设备时可使用模拟演示。", 12, True)
        note.setWordWrap(True)
        layout.addWidget(note)
        self._device_combo = QComboBox()
        self._device_combo.setEditable(True)
        self._device_combo.lineEdit().setPlaceholderText("扫描设备，或输入设备名称")
        self._device_combo.lineEdit().returnPressed.connect(self.on_connect_toggle)
        layout.addWidget(self._device_combo)
        row = QHBoxLayout()
        self._scan_btn = Button("扫描设备")
        self._scan_btn.clicked.connect(self.on_scan)
        self._connect_btn = Button("连接", primary=True)
        self._connect_btn.clicked.connect(self.on_connect_toggle)
        row.addWidget(self._scan_btn)
        row.addStretch()
        row.addWidget(self._connect_btn)
        layout.addLayout(row)
        layout.addWidget(self._rule())
        self._sim_chip = QCheckBox("模拟演示 · 不是真实心率")
        self._sim_chip.toggled.connect(self._on_sim_toggled)
        layout.addWidget(self._sim_chip)
        self._profile_combo = CapsuleCombo()
        for key in ("gaming", "desktop", "rest"):
            self._profile_combo.addItem(PROFILES[key], key)
        layout.addWidget(self._profile_combo)
        self._connection_note = label("扫描和连接状态会显示在主窗口底部。", 11, True)
        self._connection_note.setWordWrap(True)
        layout.addWidget(self._connection_note)

    def _build_live_page(self) -> QWidget:
        page = QWidget()
        layout = QVBoxLayout(page)
        layout.setContentsMargins(0, 0, 0, 0)
        layout.setSpacing(8)
        hero = QHBoxLayout()
        hero.setSpacing(28)
        self.bpm_panel = Reading()
        hero.addWidget(self.bpm_panel, 5)
        hero.addWidget(self._rule(True))
        info = QVBoxLayout()
        info.setContentsMargins(12, 16, 0, 10)
        info.addStretch()
        self._record_label = label("●  准备就绪", 14)
        self._record_label.setStyleSheet(f"color: {RED};")
        info.addWidget(self._record_label)
        timer_row = QHBoxLayout()
        duration = label("00:00")
        duration.setFont(serif(46))
        self._record_btn = Button("开始记录", primary=True)
        self._record_btn.setMinimumWidth(126)
        self._record_btn.clicked.connect(self.on_record_toggle)
        timer_row.addWidget(duration)
        timer_row.addStretch()
        timer_row.addWidget(self._record_btn)
        info.addLayout(timer_row)
        stats = QHBoxLayout()
        stats.setSpacing(20)
        self._stat_values = {"duration": duration}
        for key, title in (("avg", "平均"), ("max", "最高"), ("min", "最低")):
            stats.addWidget(label(title, 12, True))
            value = label("—")
            value.setFont(serif(25))
            stats.addWidget(value)
            self._stat_values[key] = value
        stats.addStretch()
        info.addLayout(stats)
        info.addSpacing(10)
        self._reading_detail = label("等待有效心率", 12, True)
        info.addWidget(self._reading_detail)
        info.addStretch()
        hero.addLayout(info, 6)
        layout.addLayout(hero, 3)
        chart_header = QHBoxLayout()
        chart_header.addWidget(label("心率曲线", 13))
        chart_header.addStretch()
        self._live_range = CapsuleCombo()
        self._live_range.addItem("最近 5 分钟", 300)
        self._live_range.addItem("最近 30 分钟", 1800)
        self._live_range.addItem("本次全程", 0)
        self._live_range.currentIndexChanged.connect(self._draw_live_chart)
        chart_header.addWidget(self._live_range)
        layout.addLayout(chart_header)
        self.live_chart = Curve()
        layout.addWidget(self.live_chart, 5)
        bottom = QHBoxLayout()
        self._session_caption = label("本地记录 · 数据保存在这台电脑", 11, True)
        bottom.addWidget(self._session_caption, 1)
        export = Button("导出曲线")
        export.clicked.connect(lambda: self.on_export_current())
        bottom.addWidget(export)
        show = Button("显示小窗")
        show.clicked.connect(self.on_overlay_toggle)
        bottom.addWidget(show)
        layout.addLayout(bottom)
        return page

    def _build_history_page(self) -> QWidget:
        page = QWidget()
        row = QHBoxLayout(page)
        row.setContentsMargins(0, 18, 0, 0)
        row.setSpacing(28)
        left = QVBoxLayout()
        title = label("历史记录")
        title.setFont(serif(26))
        left.addWidget(title)
        self.tree = QTableWidget(0, 3)
        self.tree.setHorizontalHeaderLabels(["日期 / 来源", "时长", "平均 / 最高"])
        self.tree.verticalHeader().hide()
        self.tree.setShowGrid(False)
        self.tree.setSelectionBehavior(QAbstractItemView.SelectionBehavior.SelectRows)
        self.tree.setSelectionMode(QAbstractItemView.SelectionMode.SingleSelection)
        self.tree.setEditTriggers(QAbstractItemView.EditTrigger.NoEditTriggers)
        self.tree.horizontalHeader().setSectionResizeMode(0, QHeaderView.ResizeMode.Stretch)
        self.tree.horizontalHeader().setSectionResizeMode(1, QHeaderView.ResizeMode.Fixed)
        self.tree.horizontalHeader().setSectionResizeMode(2, QHeaderView.ResizeMode.Fixed)
        self.tree.setColumnWidth(1, 65)
        self.tree.setColumnWidth(2, 90)
        self.tree.verticalHeader().setDefaultSectionSize(56)
        self.tree.setStyleSheet(f"QTableWidget {{ border: none; background: {PAPER}; color: {INK}; selection-background-color: #F8EAE4; selection-color: {INK}; }} QTableWidget::item {{ color: {INK}; }} QHeaderView::section {{ background: {PAPER}; color: {MUTED}; border: none; padding: 7px; font-size: 11px; }}")
        self.tree.itemSelectionChanged.connect(self.on_history_select)
        left.addWidget(self.tree, 1)
        actions = QHBoxLayout()
        refresh = Button("刷新")
        refresh.clicked.connect(self._refresh_history)
        delete = Button("删除")
        delete.clicked.connect(self.on_delete_selected)
        actions.addWidget(refresh)
        actions.addWidget(delete)
        left.addLayout(actions)
        row.addLayout(left, 4)
        row.addWidget(self._rule(True))
        right = QVBoxLayout()
        right.setSpacing(16)
        self._history_summary = label("选择一次记录，回看整段心率变化。", 14)
        self._history_summary.setWordWrap(True)
        right.addWidget(self._history_summary)
        self.history_chart = Curve()
        self.history_chart.empty_text = "还没有选中记录"
        right.addWidget(self.history_chart, 1)
        tip = label("滚轮缩放 · 拖动平移 · 悬停查看 · 双击恢复全程", 11, True)
        tip.setWordWrap(True)
        right.addWidget(tip)
        controls = QHBoxLayout()
        reset = Button("全程")
        reset.clicked.connect(self.history_chart.reset_view)
        export = Button("导出 CSV")
        export.clicked.connect(lambda: self.on_export_selected())
        controls.addWidget(reset)
        controls.addStretch()
        controls.addWidget(export)
        right.addLayout(controls)
        row.addLayout(right, 7)
        return page

    def _build_overlay_page(self) -> QWidget:
        page = QWidget()
        layout = QVBoxLayout(page)
        layout.setContentsMargins(24, 30, 24, 30)
        layout.setSpacing(20)
        heading = label("游戏中的一瞥")
        heading.setFont(serif(38))
        layout.addWidget(heading)
        layout.addWidget(label("暖白底、墨色数字与细曲线。拖动小窗即可摆放，位置会自动保存。", 13, True))
        show = Button("显示 / 隐藏小窗", primary=True)
        show.setMaximumWidth(200)
        show.clicked.connect(self.on_overlay_toggle)
        layout.addWidget(show)
        layout.addWidget(self._rule())
        layout.addWidget(label("透明度", 13))
        self._opacity = QSlider(Qt.Orientation.Horizontal)
        self._opacity.setRange(30, 100)
        self._opacity.setValue(self.store.get_int_setting("overlay_opacity", 92))
        self._opacity.setMaximumWidth(420)
        self._opacity.valueChanged.connect(self._set_overlay_opacity)
        layout.addWidget(self._opacity)
        layout.addWidget(label("小窗大小", 13))
        self._overlay_scale = QSlider(Qt.Orientation.Horizontal)
        self._overlay_scale.setRange(75, 150)
        self._overlay_scale.setValue(self.store.get_int_setting("overlay_scale", 100))
        self._overlay_scale.setMaximumWidth(420)
        self._overlay_scale.valueChanged.connect(lambda value: self._overlay.set_scale(value))
        layout.addWidget(self._overlay_scale)
        self._passthrough = QCheckBox("鼠标穿透 · 点击会交给下方游戏")
        self._passthrough.setChecked(self.store.get_setting("overlay_passthrough", "0") == "1")
        self._passthrough.toggled.connect(self._set_overlay_passthrough)
        layout.addWidget(self._passthrough)
        self._hotkey_hint = label("Ctrl+Alt+H 显示 / 隐藏小窗", 13, True)
        layout.addWidget(self._hotkey_hint)
        note = label("鼠标穿透开启后，可回此页关闭。独占全屏游戏请改为无边框窗口模式。", 12, True)
        note.setWordWrap(True)
        layout.addWidget(note)
        location = Button("打开记录目录")
        location.setMaximumWidth(200)
        location.clicked.connect(self.on_open_data_dir)
        layout.addWidget(location)
        layout.addStretch()
        return page
