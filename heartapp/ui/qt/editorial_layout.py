    def _build_overlay_page(self) -> QWidget:
        page = QWidget()
        layout = QVBoxLayout(page)
        layout.setContentsMargins(6, 8, 6, 6)
        layout.setSpacing(14)
        header = QHBoxLayout()
        title = QVBoxLayout()
        title.setSpacing(4)
        heading = label("小窗设置")
        heading.setFont(serif(26))
        title.addWidget(heading)
        title.addWidget(label("单人和联机小窗共用设置，拖动小窗可保存位置。", 12, True))
        header.addLayout(title, 1)
        show = Button("显示 / 隐藏小窗", primary=True)
        show.clicked.connect(self._toggle_active_overlay)
        header.addWidget(show)
        layout.addLayout(header)
        layout.addWidget(self._rule())

        columns = QHBoxLayout()
        columns.setSpacing(18)
        layout.addLayout(columns, 1)
        controls = QVBoxLayout()
        controls.setSpacing(10)
        columns.addLayout(controls, 1)
        preview = QVBoxLayout()
        preview.setSpacing(8)
        columns.addLayout(preview, 1)

        def slider_row(column, name, key, default, low, high, suffix, callback) -> QSlider:
            row = QHBoxLayout()
            caption = label(name, 13)
            caption.setMinimumWidth(78)
            row.addWidget(caption)
            slider = QSlider(Qt.Orientation.Horizontal)
            slider.setRange(low, high)
            slider.setValue(self.store.get_int_setting(key, default))
            slider.setAccessibleName(name)
            slider.valueChanged.connect(callback)
            row.addWidget(slider, 1)
            value_label = label(f"{slider.value()}{suffix}", 12, True)
            value_label.setFixedWidth(48)
            value_label.setAlignment(Qt.AlignmentFlag.AlignRight | Qt.AlignmentFlag.AlignVCenter)
            value_label.setBuddy(slider)
            slider.valueChanged.connect(lambda value: value_label.setText(f"{value}{suffix}"))
            row.addWidget(value_label)
            column.addLayout(row)
            return slider

        controls.addWidget(label("显示", 16))
        self._overlay_scale = slider_row(
            controls, "小窗大小", "overlay_scale", 100, 75, 150, "%", self._set_overlay_scale
        )
        self._opacity = slider_row(
            controls, "整体透明度", "overlay_opacity", 92, 30, 100, "%", self._set_overlay_opacity
        )
        curve_row = QHBoxLayout()
        caption = label("小窗曲线", 13)
        caption.setMinimumWidth(78)
        curve_row.addWidget(caption)
        self._overlay_curve = CapsuleCombo()
        for name, seconds in (("仅显示心率", 0), ("最近 15 秒", 15), ("最近 30 秒", 30), ("最近 60 秒", 60)):
            self._overlay_curve.addItem(name, seconds)
        saved = self._overlay_curve.findData(self.store.get_int_setting("overlay_curve_seconds", 60))
        self._overlay_curve.setCurrentIndex(saved if saved >= 0 else self._overlay_curve.findData(60))
        self._overlay_curve.currentIndexChanged.connect(self._set_overlay_curve)
        curve_row.addWidget(self._overlay_curve)
        curve_row.addStretch()
        controls.addLayout(curve_row)
        self._overlay_line_width = slider_row(
            controls, "曲线粗细", "overlay_line_width", 1, 1, 5, "", self._update_overlay_style_values
        )
        controls.addSpacing(8)
        controls.addWidget(self._rule())
        controls.addWidget(label("操作", 16))
        self._passthrough = QCheckBox("鼠标穿透 · 点击会交给下方游戏")
        self._passthrough.setChecked(self.store.get_setting("overlay_passthrough", "0") == "1")
        self._passthrough.toggled.connect(self._set_overlay_passthrough)
        controls.addWidget(self._passthrough)
        self._hotkey_hint = label("Ctrl+Alt+H 显示 / 隐藏小窗", 12, True)
        self._hotkey_hint.setWordWrap(True)
        controls.addWidget(self._hotkey_hint)
        note = label("独占全屏游戏请切换到无边框窗口模式。", 12, True)
        note.setWordWrap(True)
        controls.addWidget(note)
        controls.addStretch()

        preview_header = QHBoxLayout()
        preview_header.addWidget(label("预览 · 模拟数据", 16), 1)
        self._overlay_preview_light = QCheckBox("浅色底")
        self._overlay_preview_light.toggled.connect(self._refresh_overlay_preview)
        preview_header.addWidget(self._overlay_preview_light)
        preview.addLayout(preview_header)
        self._overlay_preview = QLabel()
        self._overlay_preview.setAlignment(Qt.AlignmentFlag.AlignCenter)
        self._overlay_preview.setFixedHeight(112)
        preview.addWidget(self._overlay_preview)

        self._overlay_color_buttons = {}
        colors = QHBoxLayout()
        for key, name in (("background", "背景颜色"), ("text", "文字颜色"), ("curve", "单人曲线颜色")):
            control = QVBoxLayout()
